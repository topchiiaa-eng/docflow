-- ============================================================
-- Миграция 5: владелец видит свою организацию независимо от членства.
--
-- Найдено e2e-тестом на живом бэкенде: INSERT в organizations через PostgREST
-- возвращал 42501 «new row violates row-level security policy». PostgREST
-- выполняет INSERT … RETURNING, а PostgreSQL проверяет SELECT-политику на
-- возвращаемую строку ДО срабатывания AFTER-триггера handle_new_org, который
-- делает создателя участником, — политика «члены видят свои организации»
-- в этот момент ещё ложна. Отдельная политика для владельца закрывает разрыв
-- и семантически верна сама по себе.
-- ============================================================

begin;

create policy "владелец видит свою организацию"
  on public.organizations for select to authenticated
  using (created_by = auth.uid());

commit;
